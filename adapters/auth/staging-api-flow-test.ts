import assert from "node:assert/strict";

const visit = await fetch("http://localhost:3020/community?view=spaces", { redirect: "manual" });
assert.equal(visit.status, 307);
const start = new URL(visit.headers.get("location") ?? "");
assert.equal(start.origin, "http://localhost:8017");
assert.equal(start.pathname, "/start");
assert.equal(start.searchParams.get("returnTo"), "/community?view=spaces");
const response = await fetch(start, { redirect: "manual" });
assert.equal(response.status, 302);
const authorization = new URL(response.headers.get("location") ?? "");
assert.equal(authorization.origin, "https://getfretwise-cydd.1wp.site");
assert.equal(authorization.pathname, "/wenisch-tech/keystone-oidc/oauth/authorize");
assert.equal(authorization.searchParams.get("response_type"), "code");
assert.equal(authorization.searchParams.get("code_challenge_method"), "S256");
assert.ok(authorization.searchParams.get("state"));
assert.ok(authorization.searchParams.get("nonce"));
assert.ok(authorization.searchParams.get("code_challenge"));
assert.ok(response.headers.getSetCookie().length);
const oauthCookie = response.headers.getSetCookie().map((cookie) => cookie.split(";")[0]).join("; ");
const deniedUrl = new URL("http://localhost:8017/callback");
deniedUrl.searchParams.set("error", "access_denied");
deniedUrl.searchParams.set("state", authorization.searchParams.get("state")!);
const relay = await fetch(deniedUrl, { headers: { cookie: oauthCookie }, redirect: "manual" });
assert.equal(relay.status, 302);
const denied = await fetch(relay.headers.get("location")!, { headers: { cookie: oauthCookie }, redirect: "manual" });
assert.equal(denied.status, 302);
assert.ok(!denied.headers.getSetCookie().some((cookie) => cookie.startsWith("better-auth.session_token=") && !cookie.includes("Max-Age=0")));
const unsafe = await fetch("http://localhost:8017/start?returnTo=https%3A%2F%2Fexample.com", { redirect: "manual" });
assert.notEqual(unsafe.status, 302);
const studentLogin = await fetch("http://localhost:8002/login?next=%2Fcourses%2Fcrs_123");
assert.equal(studentLogin.status, 200);
assert.match(await studentLogin.text(), /Sign in with Fretwise/);
const studentStart = await fetch("http://localhost:8017/start?target=student&returnTo=%2Fcourses%2Fcrs_123", { redirect: "manual" });
assert.equal(studentStart.status, 302);
const unsafeStudent = await fetch("http://localhost:8017/start?target=student&returnTo=%2Fapi%2Fauth%2Fsign-out", { redirect: "manual" });
assert.notEqual(unsafeStudent.status, 302);
const forged = await fetch("http://localhost:8000/api/auth/callback/fretwise-wordpress-staging?code=invalid&state=invalid", { redirect: "manual" });
assert.ok(!forged.headers.getSetCookie().some((cookie) => cookie.startsWith("better-auth.session_token=") && !cookie.includes("Max-Age=0")));
const unauthenticated = await fetch("http://localhost:8000/api/auth/get-session");
assert.equal(await unauthenticated.json(), null);
process.stdout.write("PASS: frontend and student-portal sign-in entry points; denied consent, unsafe returns and forged callbacks create no session.\n");
